const rows: Topic[] = [];
function group(category: Category, source: string, data: string) {
  for (const line of data.trim().split("\n")) {
    const [
      id,
      name,
      en,
      rank,
      intro,
      history,
      use,
      invariant,
      caveat,
      cost,
      analysis,
      analogy,
    ] = line.split("|");
    const [best, average, worst, space] = cost.split(";");
    rows.push({
      id,
      name,
      en,
      category,
      level: +rank[0],
      importance: +rank[1],
      popularity: +rank[2],
      intro,
      history,
      use,
      invariant,
      caveat,
      best,
      average,
      worst,
      space,
      analysis,
      analogy,
      source,
      input: "7, 2, 9, 4, 3, 8, 1, 6, 5, 10",
      inputHint: "2–16 个 0–99 的整数，以逗号分隔",
      mode: "numbers",
    });
  }
}
